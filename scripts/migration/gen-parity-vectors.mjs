// Writes docs/data/parity_vectors.json: fixed inputs for the pure rule functions (policy limits, approval route, advance
// notice, GSTIN check digit, TDS) together with what THIS implementation answers. A rebuild runs the same inputs through its own
// code and compares. Nothing here touches a database or the network: the Supabase client is replaced by an empty stub.
//   node scripts/migration/gen-parity-vectors.mjs          (also run by `npm run handover`)
import fs from 'fs'
import path from 'path'
import { fileURLToPath, pathToFileURL } from 'url'
import { register } from 'node:module'

// Any import of the Supabase client (or other browser-only helpers that need it) resolves to an inert stub.
const hooks = `
export async function resolve(specifier, context, next) {
  if (/(^|\\/)supabase(\\.js)?$/.test(specifier)) return { url: 'data:text/javascript,export const supabase = new Proxy({}, { get: () => { throw new Error("stubbed supabase was used") } })', shortCircuit: true }
  return next(specifier, context)
}
// Source files import siblings without an extension (Vite style); Node needs one.
export async function load(url, context, next) { return next(url, context) }
`
register('data:text/javascript,' + encodeURIComponent(hooks), import.meta.url)

const here = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(here, '..', '..')
const lib = f => pathToFileURL(path.join(ROOT, 'src', 'lib', f)).href

// Resolve extensionless relative imports by pre-loading each module with its .js name through a tiny resolver.
const extHooks = `
import fs from 'node:fs'
import { fileURLToPath } from 'node:url'
export async function resolve(specifier, context, next) {
  if (/^\\.\\.?\\//.test(specifier) && !/\\.[a-z]+$/i.test(specifier) && context.parentURL?.startsWith('file:')) {
    const base = new URL(specifier, context.parentURL)
    for (const ext of ['.js', '/index.js']) { const u = base.href + ext; try { if (fs.existsSync(fileURLToPath(u))) return next(u, context) } catch {} }
  }
  return next(specifier, context)
}
`
register('data:text/javascript,' + encodeURIComponent(extHooks), import.meta.url)

const policy = await import(lib('policyEngine.js'))
const tds = await import(lib('tds.js'))
const adv = await import(lib('advanceValidation.js'))
const tax = await import(lib('taxChecks.js'))

const dmy = d => `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`
const daysAgo = n => { const d = new Date(); d.setDate(d.getDate() - n); return dmy(d) }
const isoDaysAhead = n => { const d = new Date(); d.setDate(d.getDate() + n); return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}` }
const verdict = r => ({ passed: r.passed === true, rule: r.rule, blocking: r.blocking === true })

const out = {
  _about: 'Generated by scripts/migration/gen-parity-vectors.mjs from the live code. For each case run `input` through your implementation and compare with `expect`. Dates are given relative to the day the case is run (daysAgo / daysAhead). Amounts are INR.',
  generated_on: new Date().toISOString().slice(0, 10),
  policy: [], approval_route: [], advance: [], gstin: [], tds: [], tds_split: [],
}

// ---- policy checks (hard checks): expense in, { passed, rule, blocking } out ----
const P = (name, fn, input, build = e => e) => {
  const expense = build({ ...input })
  out.policy.push({ name, check: fn.name, input, expect: verdict(fn(expense)) })
}
const withDate = e => { if (e.daysAgo != null) { e.date = daysAgo(e.daysAgo); delete e.daysAgo } return e }
for (const n of [0, 30, 31]) P(`expense dated ${n} days ago`, policy.checkSubmissionTiming, { daysAgo: n }, withDate)
const hotel = { category: 'Lodging and Boarding' }
P('hotel, metro, base exactly 4,000 (amount 4,720)', policy.checkHotelLimit, { ...hotel, description: 'stay in Delhi', amount: 4720 })
P('hotel, metro, just over (4,721)', policy.checkHotelLimit, { ...hotel, description: 'stay in Delhi', amount: 4721 })
P('hotel, non-metro, base exactly 3,250 (amount 3,835)', policy.checkHotelLimit, { ...hotel, description: 'stay in Jaipur', amount: 3835 })
P('hotel, non-metro, just over (3,836)', policy.checkHotelLimit, { ...hotel, description: 'stay in Jaipur', amount: 3836 })
P('hotel, metro, 2 people sharing, 9,440', policy.checkHotelLimit, { ...hotel, description: 'stay in Mumbai', amount: 9440, expense_type: 'my_team', attendee_count: 2 })
P('hotel, metro, 2 people sharing, 9,441', policy.checkHotelLimit, { ...hotel, description: 'stay in Mumbai', amount: 9441, expense_type: 'my_team', attendee_count: 2 })
P('food, 750 for one person', policy.checkFoodLimit, { category: 'Food', amount: 750 })
P('food, 751 for one person', policy.checkFoodLimit, { category: 'Food', amount: 751 })
P('food, 1,500 for 2 people', policy.checkFoodLimit, { category: 'Food', amount: 1500, expense_type: 'my_team', attendee_count: 2 })
P('food, 1,501 for 2 people', policy.checkFoodLimit, { category: 'Food', amount: 1501, expense_type: 'my_team', attendee_count: 2 })
P('claim of exactly 20,000 without donor mention', policy.checkLargeClaimDonorMention, { amount: 20000, description: 'laptop' })
P('claim of 20,001 without donor mention', policy.checkLargeClaimDonorMention, { amount: 20001, description: 'laptop' })
P('claim of 20,001 with "funded by"', policy.checkLargeClaimDonorMention, { amount: 20001, description: 'laptop funded by a donor' })
P('claim of 20,001, FCRA entity, no mention (same result as any entity)', policy.checkLargeClaimDonorMention, { amount: 20001, description: 'laptop', entity: 'Nudge Lifeskills Foundation - FCRA' })
P('own car 100 km, 1,550 (limit 1,500 + 50)', policy.checkPerKmRate, { description: 'own vehicle 100 km', amount: 1550 })
P('own car 100 km, 1,551', policy.checkPerKmRate, { description: 'own vehicle 100 km', amount: 1551 })
P('bike 100 km, 550 (limit 500 + 50)', policy.checkPerKmRate, { description: 'bike 100 km', amount: 550 })
P('bike 100 km, 551', policy.checkPerKmRate, { description: 'bike 100 km', amount: 551 })

// ---- approval route from the report total (no rules table: the built-in fallback, threshold 2,00,000) ----
for (const total of [1000, 200000, 200001]) {
  const r = policy.determineApprovalRoute([{ amount: total }], [])
  out.approval_route.push({ name: `report total ${total}, no rules loaded`, input: { total, rules: [] }, expect: { levels: r.steps.slice(1) } })
}
const rules = [
  { name: 'Up to 2 lakh', min_amount: null, max_amount: 200000, mode: 'standard', levels: [{ label: 'Reporting Manager' }, { label: 'Finance Team' }] },
  { name: 'Above 2 lakh', min_amount: 200000, max_amount: null, mode: 'standard', levels: [{ label: 'Reporting Manager' }, { label: 'Functional Lead' }, { label: 'Finance Team' }] },
  { name: 'Auto test', min_amount: 5000000, max_amount: null, mode: 'auto_approve', levels: [] },
]
for (const total of [200000, 200001]) {
  const r = policy.determineApprovalRoute([{ amount: total }], rules)
  out.approval_route.push({ name: `report total ${total}, with a rules table (first match in order wins; min is exclusive, max inclusive)`, input: { total, rules }, expect: { levels: r.steps.slice(1) } })
}

// ---- advances ----
out.advance.push({ name: 'maximum advance', expect: { max_amount: adv.MAX_ADVANCE_AMOUNT, min_days_notice: adv.MIN_DAYS_NOTICE } })
for (const n of [0, 6, 7, 30]) out.advance.push({ name: `expected use ${n} days from today`, input: { daysAhead: n }, expect: { auto_rejected: adv.isAutoRejected(isoDaysAhead(n)) } })

// ---- GSTIN ----
const first14 = '19AABCP9484D1Z'
const good = first14 + tax.gstinCheckChar(first14)
const bad = first14 + (good[14] === 'A' ? 'B' : 'A')
for (const [name, g] of [['valid GSTIN (check character computed)', good], ['wrong check character', bad], ['unknown state code 99', '99AABCP9484D1Z5'], ['wrong format', 'ABC123'], ['lower case and spaces are tidied', ` ${good.toLowerCase()} `]]) {
  const r = tax.checkGstin(g)
  out.gstin.push({ name, input: { gstin: g }, expect: r ? { valid: r.valid, reason: r.reason ?? null, state: r.state ?? null, pan: r.pan ?? null } : null })
}

// ---- TDS ----
const R = [
  { id: 1, section: '194J', label: 'Professional fees', categories: ['Professional Fee', 'Consultant Fee'], payee_type: 'any', rate: 10, no_pan_rate: 20, single_threshold: 30000, annual_threshold: 50000 },
  { id: 2, section: '194C', label: 'Contractor (individual)', categories: ['Service'], payee_type: 'individual', rate: 1, no_pan_rate: 20, single_threshold: 30000, annual_threshold: 100000 },
  { id: 3, section: '194C', label: 'Contractor (others)', categories: ['Service'], payee_type: 'other', rate: 2, no_pan_rate: 20, single_threshold: 30000, annual_threshold: 100000 },
  { id: 4, section: '194BB', label: 'Prize, no limits', categories: ['Prize Challenge'], payee_type: 'any', rate: 30, no_pan_rate: 30, single_threshold: null, annual_threshold: null },
]
const PERSON = 'ABCPE1234F', COMPANY = 'AABCC1234F'
const T = (name, input) => {
  const r = tds.computeTds({ rules: R, ...input })
  out.tds.push({ name, input, expect: { status: r.status, section: r.section, rate: r.rate, amount: r.amount } })
}
T('over the single-bill limit, person PAN', { category: 'Professional Fee', pan: PERSON, base: 40000 })
T('exactly at the single-bill limit (not over)', { category: 'Professional Fee', pan: PERSON, base: 30000 })
T('under both limits', { category: 'Professional Fee', pan: PERSON, base: 20000 })
T('crosses the yearly limit: tax due on everything paid so far (catch-up)', { category: 'Professional Fee', pan: PERSON, base: 20000, ytdBase: 40000 })
T('already over the yearly limit before this bill: tax on this bill only', { category: 'Professional Fee', pan: PERSON, base: 20000, ytdBase: 60000 })
T('no PAN on record: higher of rate and no-PAN rate', { category: 'Professional Fee', pan: '', base: 40000 })
T('rule with no limits applies to every bill', { category: 'Prize Challenge', pan: PERSON, base: 1000 })
T('category no rule covers', { category: 'Food', pan: PERSON, base: 40000 })
T('payee-specific rule: individual 1%', { category: 'Service', pan: PERSON, base: 40000 })
T('payee-specific rule: others 2%', { category: 'Service', pan: COMPANY, base: 40000 })
T('base not entered', { category: 'Service', pan: PERSON, base: 0 })

const S = (name, input) => {
  const r = tds.computeTdsSplit({ rules: R, ...input })
  out.tds_split.push({ name, input, expect: { status: r.status, base: r.base, amount: r.amount, section: r.section, lines: r.lines.map(l => ({ category: l.category, amount: l.amount, tds: l.tds, status: l.status })) } })
}
S('two lines under one rule are added before the single-bill limit (20,000 + 20,000 > 30,000)', { pan: PERSON, lines: [{ category: 'Professional Fee', amount: 20000 }, { category: 'Consultant Fee', amount: 20000 }] })
S('different rules per line; GST and incidentals are not part of the lines', { pan: COMPANY, lines: [{ category: 'Professional Fee', amount: 40000 }, { category: 'Service', amount: 10000 }] })
S('yearly pieces count only toward the rule they fall under', { pan: PERSON, lines: [{ category: 'Professional Fee', amount: 20000 }], pieces: [{ category: 'Consultant Fee', base: 40000 }, { category: 'Service', base: 90000 }] })

fs.mkdirSync(path.join(ROOT, 'docs', 'data'), { recursive: true })
fs.writeFileSync(path.join(ROOT, 'docs', 'data', 'parity_vectors.json'), JSON.stringify(out, null, 2) + '\n')
const n = Object.values(out).filter(Array.isArray).reduce((s, a) => s + a.length, 0)
console.log(`Wrote docs/data/parity_vectors.json (${n} cases)`)
