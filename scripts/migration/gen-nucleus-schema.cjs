// Turns the exported schema (docs/database/schema.sql) into a version that is safe to apply to the NUCLEUS Supabase project:
// docs/database/nucleus_schema.sql. Run again whenever the schema export changes (also run by `npm run handover`).
//   node scripts/migration/gen-nucleus-schema.cjs
//
// What changes, and why (the original schema was written for a standalone tool with an open database):
//   1. A pre-flight block ABORTS the whole migration if any of the tool's tables or functions already exists in the target.
//      (The export uses CREATE TABLE IF NOT EXISTS / CREATE OR REPLACE FUNCTION, which would silently skip or overwrite.)
//   2. Every "open to everyone" policy is removed. In their place: only signed-in Nucleus employees who are active in the
//      `employees` table can read or write; the System Log and audit-access log can be READ only by admin / super_admin.
//      The same applies to the four app storage buckets plus the legacy one.
//   3. The `anon` role gets NO access to any table (the original granted it everything). `authenticated` loses TRUNCATE,
//      REFERENCES and TRIGGER.
//   4. Extensions Supabase already ships (pg_stat_statements, supabase_vault) are not re-created.
//   5. The two event triggers that log every schema change are NOT part of this file (they would log all of Nucleus's own
//      migrations). The append-only lock on system_logs (ordinary triggers) is kept.
// Role-based rules beyond "active employee" (who may approve what) stay in the application until the role mapping is settled.
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..', '..')
const SRC = fs.existsSync(path.join(ROOT, 'docs', 'database', 'schema.sql'))
  ? path.join(ROOT, 'docs', 'database', 'schema.sql')
  : path.join(ROOT, 'db_export_backup', 'migration_pack', '01_schema.sql')
const OUT = path.join(ROOT, 'docs', 'database', 'nucleus_schema.sql')

const src = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n')
const lines = src.split('\n')

const tables = [...src.matchAll(/^CREATE TABLE IF NOT EXISTS "public"\."([a-z_0-9]+)"/gm)].map(m => m[1])
const functions = [...src.matchAll(/^CREATE OR REPLACE FUNCTION public\.([a-z_0-9]+)\(/gm)].map(m => m[1])
if (tables.length < 20) throw new Error(`Only found ${tables.length} tables in ${SRC}; the export format may have changed`)

const ADMIN_READ_ONLY = new Set(['system_logs', 'audit_trail_access_log'])
const buckets = [...src.matchAll(/INSERT INTO storage\.buckets \(id, [^)]*\) VALUES \('([^']+)'/g)].map(m => m[1])

// ---- 1. filter the original ----
const out = []
let section = ''
for (const line of lines) {
  const sec = /^-- ([a-z ]+)$/.exec(line)
  if (sec) section = sec[1]
  if (/^CREATE EXTENSION IF NOT EXISTS "(pg_stat_statements|supabase_vault)"/.test(line)) continue
  if (section === 'row level security' && /^(DROP POLICY|CREATE POLICY) /.test(line)) continue // replaced below
  if (section === 'grants') {
    if (/^GRANT .* TO "anon";$/.test(line)) continue // anon gets nothing
    const g = /^GRANT (.+) ON TABLE ("public"\."[a-z_0-9]+") TO "authenticated";$/.exec(line)
    if (g) {
      const privs = g[1].split(',').map(p => p.trim()).filter(p => !['TRUNCATE', 'REFERENCES', 'TRIGGER'].includes(p))
      out.push(`GRANT ${privs.join(', ')} ON TABLE ${g[2]} TO "authenticated";`)
      continue
    }
  }
  out.push(line)
}

// ---- 2. assemble ----
const q = n => `'${n}'`
const header = `-- ${path.basename(OUT)}: the Nucleus-safe version of the tool's database schema.
-- GENERATED by scripts/migration/gen-nucleus-schema.cjs from docs/database/schema.sql. Do not edit by hand.
-- Applies to the Nucleus Supabase project as a migration (SQL editor, Supabase CLI, or scripts/migration/apply-nucleus.cjs).
-- Creates ${tables.length} tables, ${functions.length} functions, triggers, ${buckets.length} private storage buckets, and sign-in-only policies.
-- Aborts without changing anything if a clashing table or function already exists.
-- It does NOT install the schema-change event triggers and does NOT contain any data.

DO $preflight$
DECLARE
  clash_tables text;
  clash_functions text;
BEGIN
  SELECT string_agg(c.relname, ', ' ORDER BY c.relname) INTO clash_tables
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm') AND c.relname IN (${tables.map(q).join(', ')});
  SELECT string_agg(DISTINCT p.proname, ', ') INTO clash_functions
    FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
   WHERE n.nspname = 'public' AND p.proname IN (${[...functions, 'prpo_jwt_email', 'prpo_is_staff', 'prpo_is_admin'].map(q).join(', ')});
  IF clash_tables IS NOT NULL OR clash_functions IS NOT NULL THEN
    RAISE EXCEPTION 'Nucleus already has objects with the tool''s names. Nothing was changed. Tables: %. Functions: %. Check they are empty/unused, drop them deliberately, then run again.',
      coalesce(clash_tables, 'none'), coalesce(clash_functions, 'none');
  END IF;
  IF to_regclass('public.employees') IS NULL THEN
    RAISE EXCEPTION 'public.employees was not found. The sign-in-only policies read it; is this the Nucleus database?';
  END IF;
  IF (SELECT count(*) FROM information_schema.columns WHERE table_schema = 'public' AND table_name = 'employees' AND column_name IN ('email', 'is_active', 'erp_role')) <> 3 THEN
    RAISE EXCEPTION 'public.employees must have the columns email, is_active and erp_role (the access policies use them). Adjust the prpo_is_staff / prpo_is_admin functions in this file to Nucleus''s real columns first.';
  END IF;
END
$preflight$;

`

const helpers = `
-- ============================================================
-- access: only active Nucleus employees (public.employees), admin-only logs
-- ============================================================

CREATE OR REPLACE FUNCTION public.prpo_jwt_email()
 RETURNS text
 LANGUAGE sql
 STABLE
 SET search_path TO 'public'
AS $fn$
  SELECT lower(coalesce(auth.jwt() ->> 'email', ''))
$fn$;

CREATE OR REPLACE FUNCTION public.prpo_is_staff()
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'public'
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM public.employees e
     WHERE lower(e.email) = public.prpo_jwt_email() AND coalesce(e.is_active, true)
  )
$fn$;

CREATE OR REPLACE FUNCTION public.prpo_is_admin()
 RETURNS boolean
 LANGUAGE sql
 STABLE
 SECURITY DEFINER
 SET search_path TO 'public'
AS $fn$
  SELECT EXISTS (
    SELECT 1 FROM public.employees e
     WHERE lower(e.email) = public.prpo_jwt_email() AND coalesce(e.is_active, true)
       AND e.erp_role IN ('admin', 'super_admin')
  )
$fn$;

REVOKE ALL ON FUNCTION public.prpo_jwt_email(), public.prpo_is_staff(), public.prpo_is_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.prpo_jwt_email(), public.prpo_is_staff(), public.prpo_is_admin() TO authenticated, service_role;

`
const policies = []
policies.push('-- ============================================================', '-- policies (replace the original open-to-everyone ones)', '-- ============================================================', '')
for (const t of tables) {
  if (ADMIN_READ_ONLY.has(t)) {
    policies.push(`CREATE POLICY "prpo_${t}_insert" ON "public"."${t}" AS PERMISSIVE FOR INSERT TO authenticated WITH CHECK (public.prpo_is_staff());`)
    policies.push(`CREATE POLICY "prpo_${t}_select" ON "public"."${t}" AS PERMISSIVE FOR SELECT TO authenticated USING (public.prpo_is_admin());`)
  } else {
    policies.push(`CREATE POLICY "prpo_${t}_staff" ON "public"."${t}" AS PERMISSIVE FOR ALL TO authenticated USING (public.prpo_is_staff()) WITH CHECK (public.prpo_is_staff());`)
  }
}
policies.push('', `CREATE POLICY "prpo_buckets_staff" ON "storage"."objects" AS PERMISSIVE FOR ALL TO authenticated`)
policies.push(`  USING (bucket_id IN (${buckets.map(q).join(', ')}) AND public.prpo_is_staff())`)
policies.push(`  WITH CHECK (bucket_id IN (${buckets.map(q).join(', ')}) AND public.prpo_is_staff());`, '')

fs.writeFileSync(OUT, header + out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n' + helpers + policies.join('\n') + '\n')
console.log(`Wrote docs/database/nucleus_schema.sql (${tables.length} tables, ${functions.length} functions, ${buckets.length} buckets)`)
