// Writes docs/AI_PROMPTS.md: the exact source of every AI prompt and the code that calls the models, copied
// verbatim from src/ and api/ so the document can never drift from what is live. Prose explanation is in
// docs/AI_AND_OCR.md. Re-run with `npm run migration:prompts` (also run by `npm run handover`).
const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..', '..')
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8').replace(/\r\n/g, '\n')

// Split a file into its top-level `export` / `function` blocks, keyed by name, keeping the comment lines just above each.
function blocks(src) {
  const lines = src.split('\n')
  const starts = []
  lines.forEach((l, i) => { const m = /^(?:export\s+)?(?:async\s+)?function\s+([A-Za-z0-9_]+)/.exec(l); if (m) starts.push({ name: m[1], i }) })
  return starts.map((s, k) => {
    let from = s.i
    while (from > 0 && /^\s*\/\//.test(lines[from - 1])) from--
    const to = k + 1 < starts.length ? starts[k + 1].i : lines.length
    let end = to
    while (end > s.i && (/^\s*\/\//.test(lines[end - 1]) || lines[end - 1].trim() === '')) end--
    return { name: s.name, code: lines.slice(from, end).join('\n') }
  })
}

const out = []
out.push('# AI prompts and model calls (generated, verbatim)', '')
out.push('Generated by `scripts/migration/gen-ai-prompts.cjs` from the live source. **Do not edit by hand**; change the source and re-run `npm run migration:prompts`.')
out.push('How these fit together, what they are for and how their output is cleaned is explained in [`AI_AND_OCR.md`](AI_AND_OCR.md).', '')

const claude = blocks(read('src/lib/claude.js'))
const groups = [
  ['Receipt and payment-proof reading (Gemini, image in, JSON out)', ['checkDocumentQuality', 'extractReceiptData', 'tidyReceiptData', 'detectUPI', 'extractPaymentAmount']],
  ['Vendor document reading (Gemini, image or PDF page in, JSON out)', ['extractChequeDetails', 'extractPanCardDetails', 'extractGstCertDetails', 'extractMsmeCertDetails', 'extractRegistrationCertDetails']],
  ['Quotes and invoices (Gemini)', ['extractVendorQuote', 'extractInvoiceDetails']],
  ['Text summaries and checks (Groq, text in, JSON out)', ['generateManagerSummary', 'runAIVouchCheck', 'generatePRSummary', 'suggestCategory']],
]
for (const [title, names] of groups) {
  out.push(`## ${title}`, '')
  for (const n of names) {
    const b = claude.find(x => x.name === n)
    if (!b) throw new Error(`gen-ai-prompts: ${n} not found in src/lib/claude.js`)
    out.push(`### \`${n}\``, '', '```js', b.code, '```', '')
  }
}

const pol = blocks(read('src/lib/policyEngine.js')).find(x => x.name === 'checkNonReimbursableAI')
if (!pol) throw new Error('gen-ai-prompts: checkNonReimbursableAI not found')
out.push('## Policy check on an expense (Groq)', '', '### `checkNonReimbursableAI` (src/lib/policyEngine.js)', '', '```js', pol.code, '```', '')

for (const [title, file] of [['Gemini client (vision): model, settings, retries', 'src/lib/gemini.js'], ['Groq client (text): model and settings', 'src/lib/groq.js'], ['Browser-to-model proxy (server route)', 'api/ai/proxy.js']]) {
  out.push(`## ${title}`, '', `Source: \`${file}\``, '', '```js', read(file).trimEnd(), '```', '')
}

fs.writeFileSync(path.join(ROOT, 'docs', 'AI_PROMPTS.md'), out.join('\n'))
console.log(`Wrote docs/AI_PROMPTS.md (${out.length} lines)`)
